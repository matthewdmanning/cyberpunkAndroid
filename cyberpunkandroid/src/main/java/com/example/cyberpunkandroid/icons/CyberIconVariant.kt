package com.example.cyberpunkandroid.icons

/**
 * Visual rendering variants for [CyberIcon].
 */
enum class CyberIconVariant {
    /** Standard geometric vector outline stroke rendering. */
    Outline,
    /** Filled solid vector silhouette geometry. */
    Solid,
    /** Dual-layer rendering with translucent fill wash beneath sharp outline stroke. */
    Duotone,
    /** Chromatic aberration effect with offset cyan and magenta ghost channels. */
    Overload
}
